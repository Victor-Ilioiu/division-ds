import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolveTokens } from './lib/resolve-tokens.mjs'
import { resolveComponentTokens } from './lib/resolve-component-tokens.mjs'
import { checkUsage, measuredNotes, tokenManifest } from './lib/token-usage.mjs'

const primitives = JSON.parse(readFileSync('tokens/primitive/color.json', 'utf8'))
const spacing = JSON.parse(readFileSync('tokens/primitive/spacing.json', 'utf8'))
const motion = JSON.parse(readFileSync('tokens/primitive/motion.json', 'utf8'))
const dark = JSON.parse(readFileSync('tokens/semantic/color.dark.json', 'utf8'))
const light = JSON.parse(readFileSync('tokens/semantic/color.light.json', 'utf8'))
const control = JSON.parse(readFileSync('tokens/component/control.json', 'utf8'))
const usage = JSON.parse(readFileSync('tokens/usage.json', 'utf8'))

const toCssBlock = flat =>
  Object.entries(flat).map(([k, v]) => `  ${k}: ${v};`).join('\n')

const darkTokens = resolveTokens(primitives, dark)
const lightTokens = resolveTokens(primitives, light)

// The component layer emits one `var()` block serving BOTH themes, so an alias is only safe if
// the semantic token it names exists in both. Intersecting the two key sets is what makes a
// half-added token (present in dark, forgotten in light) a build failure instead of an element
// that paints unstyled in one theme only.
const semanticVarsInBothThemes = Object.keys(darkTokens).filter(k => k in lightTokens)

const colorUtilities = Object.entries(primitives.color.primitive)
  .map(([name, ramp]) =>
    Object.entries(ramp).map(([stop, tok]) => `  --color-${name}-${stop}: ${tok.$value};`).join('\n')
  )
  .join('\n')

const spacingUtilities = Object.entries(spacing.spacing)
  .map(([step, tok]) => `  --spacing-${step}: ${tok.$value};`)
  .join('\n')

const durationUtilities = Object.entries(motion.duration)
  .map(([name, tok]) => `  --duration-${name}: ${tok.$value};`)
  .join('\n')

const easeUtilities = Object.entries(motion.ease)
  .map(([name, tok]) => `  --ease-${name}: ${tok.$value};`)
  .join('\n')

// Primitives go in a plain :root rule, not @theme: Tailwind v4's JIT tree-shakes any @theme
// variable that no scanned class actually references, and nothing in this app uses the
// Tailwind-generated utility class form (bg-signal-500, duration-180, ...) -- every component
// reads these through var(--...) instead. A plain rule is never pruned.
const css = `/* GENERATED by scripts/build-tokens.mjs -- do not hand-edit. Source: JSON files under tokens/ */
:root {
${colorUtilities}
${spacingUtilities}
${durationUtilities}
${easeUtilities}
}

:root, [data-theme="dark"] {
${toCssBlock(darkTokens)}
}

[data-theme="light"] {
${toCssBlock(lightTokens)}
}

/* Component layer: var() references, not resolved values, so one block serves both themes.
   See scripts/lib/resolve-component-tokens.mjs for why.

   Declared on [data-theme] as well as :root. A var() inside a custom property is resolved on the
   element that declares it and inherited as a finished value, so with :root alone a subtree that
   pins its own theme (the demo homepage's hero sets data-theme="dark" over its always-dark 3D
   scene) would get the semantic colours of its own theme and the component colours of the
   page's: a secondary Button with light-theme text on a dark stage. Re-declaring the block
   wherever a theme is set makes each alias resolve against the theme it sits in. */
:root, [data-theme] {
${toCssBlock(resolveComponentTokens(control, semanticVarsInBothThemes))}
}
`

// The same set again as data, for an agent: every token with what it is for. A token nobody has
// described is one an agent picks by guessing from its name, so a missing sentence stops the build.
const fromCss = block =>
  Object.fromEntries(block.split('\n').map(line => line.trim().replace(/;$/, '').split(/: (.*)/s).slice(0, 2)))
const primitive = fromCss([colorUtilities, spacingUtilities, durationUtilities, easeUtilities].join('\n'))
const component = resolveComponentTokens(control, semanticVarsInBothThemes)
const described = [
  ...Object.keys(primitive).filter(name => !name.startsWith('--color-')),
  ...Object.keys(darkTokens),
  ...Object.keys(component),
]
const problems = checkUsage(described, usage)
if (problems.length > 0) {
  console.error(`Token usage: ${problems.length} problem(s).\n  ` + problems.join('\n  '))
  process.exit(1)
}

const manifest = {
  generatedBy: 'scripts/build-tokens.mjs',
  rule: 'Components and screens use semantic and component tokens only, as var(--name). Primitive colour ramps (--color-<ramp>-<stop>) are the raw material the semantic layer is built from, not a palette to pick from.',
  tokens: tokenManifest({
    primitive,
    semanticDark: darkTokens,
    semanticLight: lightTokens,
    component,
    usage,
    notesDark: measuredNotes(dark),
    notesLight: measuredNotes(light),
  }),
}
const outputs = {
  'src/styles/tokens.css': css,
  'public/manifest/tokens.json': JSON.stringify(manifest, null, 2) + '\n',
}

// `--check` writes nothing: it is what `npm run verify` runs, so that an agent told not to touch
// other files can still run every gate. It fails when an output is missing or out of date.
if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs)
    .filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text)
    .map(([path]) => path)
  if (stale.length > 0) {
    console.error(`Token outputs are stale: ${stale.join(', ')}.\nRun: npm run tokens`)
    process.exit(1)
  }
  console.log(`Token outputs are current: ${manifest.tokens.length} tokens, ${described.length} described.`)
} else {
  mkdirSync('public/manifest', { recursive: true })
  for (const [path, text] of Object.entries(outputs)) writeFileSync(path, text)
  console.log(
    `Wrote src/styles/tokens.css and public/manifest/tokens.json (${manifest.tokens.length} tokens, ${described.length} described)`
  )
}
