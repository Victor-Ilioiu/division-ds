import { describe, it, expect } from 'vitest'
import { createRef } from 'react'
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { axeClean } from '../../../test/axe'
import { AiLabel } from './AiLabel'

const why = 'Drafted from the last three orders. Check the quantities before sending.'

describe('AiLabel', () => {
  it('without an explanation is static text, not a button', () => {
    render(<AiLabel />)
    expect(screen.getByText('Generated by AI')).toBeInTheDocument()
    expect(screen.queryByRole('button')).toBeNull()
  })

  it('with an explanation is a collapsed disclosure that opens and closes', async () => {
    render(<AiLabel explanation={why} />)
    const button = screen.getByRole('button', { name: 'Generated by AI' })
    expect(button).toHaveAttribute('aria-expanded', 'false')
    expect(screen.getByText(why, { selector: 'div' }).closest('[hidden]')).not.toBeNull()

    await userEvent.click(button)
    expect(button).toHaveAttribute('aria-expanded', 'true')
    const panel = document.getElementById(button.getAttribute('aria-controls')!)
    expect(panel).not.toHaveAttribute('hidden')
    expect(panel).toHaveTextContent(why)

    await userEvent.keyboard('{Enter}')
    expect(button).toHaveAttribute('aria-expanded', 'false')
    expect(button).toHaveFocus()
  })

  it('lists sources as links through renderLink', async () => {
    render(
      <AiLabel
        explanation={why}
        sources={[{ label: 'Order 1042', href: '/orders/1042' }]}
        renderLink={({ href, ...rest }) => <a data-router="" href={href} {...rest} />}
      />
    )
    await userEvent.click(screen.getByRole('button'))
    const link = screen.getByRole('link', { name: 'Order 1042' })
    expect(link).toHaveAttribute('href', '/orders/1042')
    expect(link).toHaveAttribute('data-router')
  })

  it('takes its own words', () => {
    render(<AiLabel label="AI summary" explanation={why} />)
    expect(screen.getByRole('button', { name: 'AI summary' })).toBeInTheDocument()
  })

  it('merges className and forwards a ref to the root', () => {
    const ref = createRef<HTMLDivElement>()
    render(<AiLabel ref={ref} className="mt-4" />)
    expect(ref.current).toHaveClass('mt-4')
    expect(ref.current).toHaveClass('text-sm')
  })

  it('is axe clean, closed and open', async () => {
    const { container } = render(<AiLabel explanation={why} sources={[{ label: 'Order 1042', href: '/orders/1042' }]} />)
    expect(await axeClean(container)).toHaveNoViolations()
    await userEvent.click(screen.getByRole('button'))
    expect(await axeClean(container)).toHaveNoViolations()
  })
})
