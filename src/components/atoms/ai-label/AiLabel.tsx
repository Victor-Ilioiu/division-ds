import { useId, useState, type HTMLAttributes, type ReactNode, type Ref } from 'react'
import { ChevronDown, Sparkles } from 'lucide-react'
import { cn } from '../../../lib/cn'
import { renderAnchor, type LinkRenderProps } from '../../../lib/render-link'
import { linkVariants } from '../link/Link'

export type AiLabelSource = { label: string; href: string }

export type AiLabelProps = HTMLAttributes<HTMLDivElement> & {
  /** The words of the mark. */
  label?: string
  /** Why this is AI content and what to do about it. Without it the mark is static text. */
  explanation?: ReactNode
  /** Where the content came from, listed under the explanation. Needs `explanation`. */
  sources?: AiLabelSource[]
  renderLink?: (props: LinkRenderProps) => ReactNode
  ref?: Ref<HTMLDivElement>
}

const MARK = 'inline-flex items-center gap-1.5 font-mono text-xs font-semibold uppercase tracking-[0.18em] text-[var(--color-ai-text)]'

/**
 * Marks content as made by AI (Carbon's AI label; GitLab Pajamas' "Generated by AI · Verify before
 * use") and, on request, says why. The why is an inline disclosure, a button with aria-expanded
 * that shows a region right under it, not a Tooltip or a Popover:
 *
 * - A Tooltip holds a phrase, never links, and a touch screen never shows it; the sources are links.
 * - A Popover would be the system's first, and a whole overlay (portal, focus return, outside
 *   click, collision) for two sentences. The disclosure is one button and one region, keyboard
 *   and screen reader for free: Enter or Space toggles, the region follows the button in the
 *   reading order, and nothing moves focus.
 *
 * The cost is that opening it pushes what is below down. For a label above a block of AI content
 * that is the right place for the why anyway.
 */
export function AiLabel({
  label = 'Generated by AI',
  explanation,
  sources,
  renderLink = renderAnchor,
  className,
  ref,
  ...rest
}: AiLabelProps) {
  const [open, setOpen] = useState(false)
  const panelId = `${useId()}-why`
  const icon = <Sparkles aria-hidden="true" className="w-3.5 h-3.5 shrink-0" />

  return (
    <div ref={ref} className={cn('text-sm', className)} {...rest}>
      {explanation == null ? (
        <span className={MARK}>
          {icon}
          {label}
        </span>
      ) : (
        <>
          <button
            type="button"
            aria-expanded={open}
            aria-controls={panelId}
            onClick={() => setOpen(o => !o)}
            className={cn(
              MARK,
              'cursor-pointer hover:underline underline-offset-4',
              'focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[var(--color-focus-ring)]'
            )}
          >
            {icon}
            {label}
            <ChevronDown aria-hidden="true" className={cn('w-3.5 h-3.5 shrink-0', open && 'rotate-180')} />
          </button>
          <div
            id={panelId}
            hidden={!open}
            className="mt-2 border-l-2 border-[var(--color-ai-border)] pl-3 text-[var(--color-text-secondary)]"
          >
            <div>{explanation}</div>
            {sources && sources.length > 0 ? (
              <>
                <p className="mt-2 font-mono text-xs font-semibold uppercase tracking-[0.18em] text-[var(--color-text-muted)]">Sources</p>
                <ul className="mt-1 space-y-1">
                  {sources.map(source => (
                    <li key={source.href}>
                      {renderLink({ href: source.href, className: linkVariants(), children: source.label })}
                    </li>
                  ))}
                </ul>
              </>
            ) : null}
          </div>
        </>
      )}
    </div>
  )
}
